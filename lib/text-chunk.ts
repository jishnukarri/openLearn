// Fixed-size chunking with overlap — simple and good enough for grounding
// short GCSE-topic reference documents (spec extracts, worksheets, notes).
// No semantic splitting; each chunk is embedded independently.
export function chunkText(text: string, size = 1000, overlap = 150): string[] {
  const clean = text.replace(/\s+/g, " ").trim();
  if (!clean) return [];

  const chunks: string[] = [];
  let start = 0;
  while (start < clean.length) {
    const end = Math.min(start + size, clean.length);
    chunks.push(clean.slice(start, end));
    if (end === clean.length) break;
    start = end - overlap;
  }
  return chunks;
}
